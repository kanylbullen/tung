import java.text.Normalizer;
import java.util.ArrayList;
import java.util.List;

/**
 * Writes core/src/commonMain/kotlin/io/github/kanylbullen/tung/core/DiacriticTables.kt
 * from the JDK's Unicode tables, so that core can fold and compose diacritics
 * without java.text.Normalizer (which Kotlin Multiplatform does not have).
 *
 *   java core/tools/GenDiacritics.java > core/src/commonMain/kotlin/io/github/kanylbullen/tung/core/DiacriticTables.kt
 *
 * Two tables, both over the Basic Multilingual Plane:
 *
 *  - FOLDS: every character whose canonical decomposition (NFD) minus the
 *    non-spacing marks (Mn) is not the character itself: "À" -> "A", the
 *    ohm sign -> Greek omega, a Tibetan vowel sign made of two marks -> "".
 *  - COMPOSITIONS: every (base, mark) pair that NFC composes into one
 *    character, stepwise: "a" + ring -> "å", and "å" + acute -> "ǻ".
 *
 * DiacriticTablesTest compares the tables with the running JDK's Normalizer
 * over the whole plane; a newer Unicode may need a regeneration.
 */
public class GenDiacritics {
    public static void main(String[] args) {
        List<String> folds = new ArrayList<>();
        List<String> compositions = new ArrayList<>();
        List<String> markDecompositions = new ArrayList<>();
        for (int cp = 0; cp <= 0xFFFF; cp++) {
            if (Character.isSurrogate((char) cp) || isOutsideScope(cp)) continue;
            if (Character.getType((char) cp) == Character.NON_SPACING_MARK) {
                // A mark on its own is dropped by category at run time, so the fold table leaves it out;
                // but a mark that is itself a sequence of marks (U+0344) must be expanded before composing.
                String nfd = Normalizer.normalize(String.valueOf((char) cp), Normalizer.Form.NFD);
                if (!nfd.equals(String.valueOf((char) cp))) markDecompositions.add((char) cp + nfd);
                continue;
            }
            String c = String.valueOf((char) cp);
            String nfd = Normalizer.normalize(c, Normalizer.Form.NFD);
            StringBuilder folded = new StringBuilder();
            for (int i = 0; i < nfd.length(); i++) {
                char x = nfd.charAt(i);
                if (Character.getType(x) != Character.NON_SPACING_MARK) folded.append(x);
            }
            if (!folded.toString().equals(c)) folds.add(c + folded);
            // Stepwise composition: the prefix of the decomposition composes to one
            // character, and that character with the last mark composes back to c.
            if (nfd.length() >= 2 && Character.getType(nfd.charAt(nfd.length() - 1)) == Character.NON_SPACING_MARK) {
                String prefix = Normalizer.normalize(nfd.substring(0, nfd.length() - 1), Normalizer.Form.NFC);
                String last = nfd.substring(nfd.length() - 1);
                if (prefix.length() == 1 && Normalizer.normalize(prefix + last, Normalizer.Form.NFC).equals(c)) {
                    compositions.add(prefix + last + c);
                }
            }
        }
        StringBuilder out = new StringBuilder();
        out.append("package io.github.kanylbullen.tung.core\n\n");
        out.append("// Generated by core/tools/GenDiacritics.java from the JDK's Unicode tables; do not edit.\n");
        out.append("// Each entry is a character followed by what it folds to, entries separated by U+0001.\n");
        out.append("internal const val DIACRITIC_FOLDS: String =\n");
        appendChunks(out, folds);
        out.append("\n// Each entry is a base, a non-spacing mark and the character NFC composes them into.\n");
        out.append("internal const val DIACRITIC_COMPOSITIONS: String =\n");
        appendChunks(out, compositions);
        out.append("\n// Each entry is a non-spacing mark followed by the marks it canonically decomposes into.\n");
        out.append("internal const val DIACRITIC_MARK_DECOMPOSITIONS: String =\n");
        appendChunks(out, markDecompositions);
        System.out.print(out);
    }

    /**
     * Hangul syllables (which decompose into jamo, not marks) and the CJK
     * compatibility ideographs (each a singleton of a unified ideograph) are
     * not diacritic folding and would be two thirds of the table; a search
     * for them matches them as typed.
     */
    private static boolean isOutsideScope(int cp) {
        return (cp >= 0xAC00 && cp <= 0xD7A3) || (cp >= 0xF900 && cp <= 0xFAFF);
    }

    /** One string literal per line of at most 24 entries, joined with +, every character escaped. */
    private static void appendChunks(StringBuilder out, List<String> entries) {
        int perLine = 24;
        for (int i = 0; i < entries.size(); i += perLine) {
            out.append("    \"");
            for (int j = i; j < Math.min(i + perLine, entries.size()); j++) {
                for (char ch : entries.get(j).toCharArray()) out.append(String.format("\\u%04X", (int) ch));
                out.append("\\u0001");
            }
            out.append('"');
            out.append(i + perLine < entries.size() ? " +\n" : "\n");
        }
        if (entries.isEmpty()) out.append("    \"\"\n");
    }
}
